import type { CollectionEntry } from 'astro:content';

/** Mainstream data-center hubs; countries outside this set (or explicitly tagged) appear in 奇葩小国. */
const MAINSTREAM_COUNTRIES = new Set([
  'US',
  'CN',
  'HK',
  'MO',
  'TW',
  'JP',
  'SG',
  'KR',
  'DE',
  'GB',
  'UK',
  'NL',
  'FR',
  'CA',
  'AU',
]);

const EXOTIC_KEYWORDS = new Set([
  '奇葩小国',
  '冷门地区',
  '冷门线路',
  '冷门网络',
  '小众机房',
  'exotic',
]);

export function isExoticPost(post: CollectionEntry<'posts'>): boolean {
  const { country, categories = [], tags = [] } = post.data;
  for (const token of [...categories, ...tags]) {
    if (
      EXOTIC_KEYWORDS.has(token.trim().toLowerCase()) ||
      EXOTIC_KEYWORDS.has(token.trim())
    ) {
      return true;
    }
  }
  return Boolean(
    country && country !== 'unspecified' && !MAINSTREAM_COUNTRIES.has(country),
  );
}

